def test_verify_notebook_ignores_markdown_and_counts_by_diff():
    """LT1: verify_build said the three pipeline notebooks differ on 913, 399 and 970 lines; Fabric had rewritten the
    first markdown cell, and the positional comparison counted every later line."""
    from fabric_backend.verify_build import compare_notebook
    dry = ("# Fabric notebook source\n\n# MARKDOWN ********************\n\n# # Silver tables\n#\n# Generated by Krusgraph\n\n"
           "# PARAMETERS CELL ********************\n\nA = 1\n\n# CELL ********************\n\nb = 2\nc = 3\nd = 4\n")
    fabric = dry.replace("# # Silver tables\n#\n# Generated by Krusgraph", "# # Silver tables\n# # Generated by Krusgraph")
    assert compare_notebook(dry, fabric)["differences"] == []
    one_more = fabric.replace("b = 2\n", "b = 2\nx = 9\n")
    d = compare_notebook(dry, one_more)["differences"]
    assert len(d) == 1 and "on 1 line(s)" in d[0]["said"] and "'x = 9' in Fabric" in d[0]["said"]
    changed = fabric.replace("A = 1", "A = 2")
    assert "on 1 line(s)" in compare_notebook(dry, changed)["differences"][0]["said"]
