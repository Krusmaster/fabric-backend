"""LT1 (live test, 17 Nov 2026): validate_plan's check card gave three different amount checks the same id
(amount:sap_vbap over sap_vbep, sap_lips and sap_vbrp). Every row of the card needs an id of its own."""
from fabric_backend import sap_demo
from fabric_backend.evidence import validate
from fabric_backend.infer import plan as make_plan
from fabric_backend.mcp_apps_next import check_rows


def test_check_ids_are_unique_on_the_sap_demo():
    s, execute = sap_demo.sqlite(schema="dbo")
    p = make_plan(s)
    full = validate(p, execute, max_items=200)
    rows = check_rows(p, full)["rows"]
    ids = [r["id"] for r in rows]
    assert len(ids) == len(set(ids)), sorted(i for i in ids if ids.count(i) > 1)
    amounts = [r for r in rows if r["kind"] == "amount"]
    assert any(r["id"] == "amount:sap_vbap>sap_vbep" for r in amounts)
    assert any(r["id"] == "amount:sap_vbak>sap_vbap" for r in amounts)


def test_silver_says_the_plan_counted_the_sap_keys():
    """LT1: create_silver_notebook's dry run on the SAP demo said the 17 pack keys were "not ... counted in the rows"
    while the same plan had counted all 17 unique. Rows are still kept (n208); the text now says what was counted."""
    from fabric_backend import silver
    s, execute = sap_demo.sqlite(schema="dbo")
    p = make_plan(s, execute=execute, profile=True)
    spec = silver.spec(p, {"item_name": "demo_lh"})
    vbak = next(t for t in spec["tables"] if t["table"] == "sap_vbak")
    assert vbak["dedupe"] is False and vbak["key_counted_unique"] is True
    assert "counted unique in the rows when the plan was made" in vbak["key_basis"]
    note = silver.dedupe_note(spec)
    assert "not declared, given or counted in the rows" not in note
    assert "counted them unique in the rows today" in note or "of them unique in the rows today" in note


