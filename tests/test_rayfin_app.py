def test_the_app_imports_no_entity_class_and_no_decorator(shop):
    """Importing the decorated classes stopped the build on 5 November; the app takes only types from schema.ts."""
    files = rayfin_files(shop, "shop", page_table="orders")
    for path in ("src/lib/connectors.ts", "src/pages/OrdersPage.tsx"):
        imports = _imports(files[path])
