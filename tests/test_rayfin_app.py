"""n109: the app side of the generated Rayfin files — src/lib/connectors.ts, the data page, rayfin/tsconfig.json.

The run of 5 November 2026 (Rayfin 1.36.2) needed three hand steps: `connector add` printed "Wired 0", the template's
page did not show data, and importing the entity classes (with their decorators) stopped the app build. These tests
check that the generated files cover them, and compile the generated project with `tsc` against the versions pinned in
tests/fixtures/rayfin_check (package.json, package-lock.json): @microsoft/rayfin-* 1.36.2 and TypeScript 5.7.3.

The compile test needs node and npm. It installs the pinned packages into tests/fixtures/rayfin_check/node_modules
(git-ignored; about 400 MB, a minute) when they are not there. Without npm it is skipped; on CI (CI=true) a missing npm
or a failed install fails it instead.
"""
from __future__ import annotations

import csv
import json
import os
import re
import shutil
import subprocess
from pathlib import Path

import pytest

from fabric_backend import Schema, plan
from fabric_backend.rayfin import RAYFIN_TSCONFIG, RAYFIN_TSCONFIG_PATH, rayfin_files, write_rayfin

ROOT = Path(__file__).resolve().parent.parent
EX = ROOT / "examples"
CHECK = ROOT / "tests" / "fixtures" / "rayfin_check"
TEMPLATE = CHECK / "node_modules" / "@microsoft" / "rayfin-cli" / "templates" / "data-app"
SCHEMAS = ROOT / "tests" / "fixtures" / "schemas"


def _rows(name):
    with open(EX / name, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


@pytest.fixture(scope="module")
def shop():
    keys: dict[str, list[str]] = {}
    for r in _rows("keys.csv"):
        keys.setdefault(r["table_name"], []).append(r["column_name"])
    return plan(Schema.from_information_schema(_rows("columns.csv")), keys)


def _imports(ts: str) -> list[str]:
    return re.findall(r"^import [^;]*;", ts, flags=re.M | re.S)


def test_the_wiring_the_page_and_the_rayfin_tsconfig_are_generated(shop):
    files = rayfin_files(shop, "shop")
    assert {"src/lib/connectors.ts", "src/pages/OrderItemsPage.tsx", "rayfin/tsconfig.json",
            "rayfin/connectors/shop/schema.ts"} <= set(files)
    wiring = files["src/lib/connectors.ts"]
    for part in ("export type AppConnectorsSchema = {\n  shop: ShopSchema;\n};", "export const connectorConfigs = {",
                 "connector: 'fabric-sqlanalytics',", "operations: ['read'],",
                 "} satisfies Record<keyof AppConnectorsSchema, ConnectorConfig>;",
                 "export const connectorRuntimes: ConnectorsRuntime = {};",
                 "import { ConnectorsRayfinClient, resolveRayfinConfig } from '@microsoft/rayfin-client';",
                 "connectors: connectorConfigs,", "export function getConnectorsClient()",
                 "OrderItems: ['orderId', 'lineNo', 'productId', 'quantity', 'timestamp'] satisfies (keyof OrderItems)[],"):
        assert part in wiring, part
    # no CLI marker, not even in a comment: `rayfin connector add` rewrites a file that contains it anywhere
    # (connector-wiring.js, isSafeToRewrite: contents.includes(GENERATED_MARKER)), with the entity classes imported
    assert "@generated by" not in wiring
    page = files["src/pages/OrderItemsPage.tsx"]
    assert "const COLUMNS = ['orderId', 'lineNo', 'productId', 'quantity', 'timestamp'] as const;" in page
    assert ".select([...COLUMNS])" in page and ".orderBy({ timestamp: 'desc' })" in page and ".first(ROWS)" in page
    assert "client.connectors.shop.OrderItems" in page and "export default OrderItemsPage;" in page
    assert files[RAYFIN_TSCONFIG_PATH] == RAYFIN_TSCONFIG and json.loads(RAYFIN_TSCONFIG)["compilerOptions"]["noEmit"] is False


def test_the_app_imports_no_entity_class_and_no_decorator(shop):
    """Importing the decorated classes stopped the build on 5 November; the app takes only types from schema.ts."""
    files = rayfin_files(shop, "shop", page_table="orders")
    for path in ("src/lib/connectors.ts", "src/pages/OrdersPage.tsx"):
        imports = _imports(files[path])
        assert imports, path
        assert not any("@microsoft/rayfin-core" in i for i in imports), path      # where the decorators live
        for i in imports:
            if "rayfin/connectors/" in i:
                assert i.startswith("import type {"), (path, i)
        assert "@entity" not in files[path] and "@one(" not in files[path]
    assert "import type { Orders } from '../../rayfin/connectors/shop/schema';" in files["src/pages/OrdersPage.tsx"]


def test_masked_columns_are_left_out_of_the_page_and_the_default_columns(shop):
    files = rayfin_files(shop, "shop", page_table="customers")
    page = files["src/pages/CustomersPage.tsx"]
    cols = re.search(r"const COLUMNS = \[(.*)\] as const;", page).group(1)
    assert cols == "'customerId', 'country'"                                   # customers.name looks like a person's name
    assert "personal data by name (Krusgraph's privacy rules): name." in page
    wiring = files["src/lib/connectors.ts"]
    assert "Customers: ['customerId', 'country'] satisfies" in wiring
    assert "Addresses: ['addressId', 'customerId'] satisfies" in wiring          # addresses.city
    readme = files["rayfin/connectors/shop/README.generated.md"]
    assert "addresses.city, customers.name" in readme
    # the entity classes still describe every column: the connector reads the table, the app chooses what to show
    assert "@text() name!: string;" in files["rayfin/connectors/shop/Customers.ts"]


def test_the_page_table_and_what_latest_means(shop):
    assert "src/pages/OrderItemsPage.tsx" in rayfin_files(shop, "shop")                       # the fact table
    cats = rayfin_files(shop, "shop", page_table="Categories")["src/pages/CategoriesPage.tsx"]
    assert ".orderBy({ id: 'desc' })" in cats and "with the highest id (its key; the table has no date column)" in cats
    assert "<h1 className=\"mb-4 text-xl font-semibold\">categories: 20 rows</h1>" in cats
    nokey = plan(Schema.from_information_schema([{"table_schema": "dbo", "table_name": "notes", "column_name": "body",
                                                   "data_type": "varchar", "ordinal_position": "1"}]))
    page = rayfin_files(nokey, "x")["src/pages/NotesPage.tsx"]
    assert ".orderBy" not in page and "no date column and no key" in page
    with pytest.raises(ValueError, match="page_table 'nope'"):
        rayfin_files(shop, "shop", page_table="nope")
    with pytest.raises(ValueError, match="page_table"):
        rayfin_files(shop, "shop", tables=["orders"], page_table="customers")
    hyphen = rayfin_files(shop, "store-sales", tables=["orders", "customers"], page_table="orders")
    assert "client.connectors['store-sales'].Orders" in hyphen["src/pages/OrdersPage.tsx"]
    assert "  'store-sales': StoreSalesSchema;" in hyphen["src/lib/connectors.ts"]


def test_write_rayfin_keeps_the_projects_own_tsconfig(shop, tmp_path, capsys):
    from fabric_backend import cli
    own = tmp_path / "rayfin" / "tsconfig.json"
    own.parent.mkdir(parents=True)
    own.write_text('{"extends": "../tsconfig.json"}\n', encoding="utf-8")
    assert cli.main(["rayfin", str(EX / "columns.csv"), "--keys", str(EX / "keys.csv"), "--connector", "shop",
                     "--page-table", "orders", "--out", str(tmp_path)]) == 0
    assert own.read_text(encoding="utf-8") == '{"extends": "../tsconfig.json"}\n'
    out = capsys.readouterr().out
    assert "kept" in out and "tsconfig.json (the project's own)" in out
    assert (tmp_path / "src" / "pages" / "OrdersPage.tsx").exists() and (tmp_path / "src" / "lib" / "connectors.ts").exists()
    fresh = tmp_path / "fresh"
    write_rayfin(rayfin_files(shop, "shop"), fresh)
    assert (fresh / RAYFIN_TSCONFIG_PATH).read_text(encoding="utf-8") == RAYFIN_TSCONFIG


def test_the_example_is_the_generated_output(shop):
    """examples/rayfin/ is an app root: what `fabric-backend rayfin examples/columns.csv --keys examples/keys.csv
    --connector shop --out examples/rayfin` writes."""
    files = rayfin_files(shop, "shop")
    on_disk = {p.relative_to(EX / "rayfin").as_posix() for p in (EX / "rayfin").rglob("*") if p.is_file()}
    assert on_disk == set(files)
    for rel, content in files.items():
        assert (EX / "rayfin" / rel).read_text(encoding="utf-8") == content, rel


# --- the compile check ----------------------------------------------------------------------------------------------

def _need(msg: str):
    if os.environ.get("CI"):
        pytest.fail(msg)
    pytest.skip(msg)


@pytest.fixture(scope="module")
def node_modules():
    """The pinned packages, installed with `npm ci` from tests/fixtures/rayfin_check/package-lock.json when missing."""
    want = json.loads((CHECK / "package.json").read_text(encoding="utf-8"))["devDependencies"]

    def installed() -> bool:
        for name, version in want.items():
            pj = CHECK / "node_modules" / name / "package.json"
            if not pj.exists() or json.loads(pj.read_text(encoding="utf-8"))["version"] != version:
                return False
        return True

    if not installed():
        npm = shutil.which("npm")
        if not shutil.which("node") or not npm:
            _need("node and npm are needed to compile the generated Rayfin project")
        r = subprocess.run([npm, "ci", "--ignore-scripts", "--no-audit", "--no-fund"], cwd=CHECK, capture_output=True,
                           text=True, timeout=900)
        if r.returncode != 0 or not installed():
            _need(f"npm ci in {CHECK} failed:\n{r.stdout[-2000:]}\n{r.stderr[-2000:]}")
    return CHECK / "node_modules"


def _project(root: Path, node_modules: Path, files: dict[str, str]) -> Path:
    """A project laid out like the `dataapp` template: its package.json ("type": "module"), tsconfig.json and
    src/vite-env.d.ts from @microsoft/rayfin-cli 1.36.2, plus the generated files. The rest of the template's src/ is
    not copied: its imports need packages the generated files do not use."""
    root.mkdir(parents=True)
    for rel in ("package.json", "tsconfig.json", "src/vite-env.d.ts"):
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(TEMPLATE / rel, root / rel)
    (root / "node_modules").symlink_to(node_modules, target_is_directory=True)
    write_rayfin(files, root)
    return root


def _tsc(root: Path, config: str) -> subprocess.CompletedProcess:
    # The template's tsconfig.json keeps its build info in node_modules/.tmp, which is the shared fixture here: each
    # compile gets its own file, so no project's incremental state decides what another one emits.
    info = root / f".tsbuildinfo-{Path(config).parent.name or 'app'}"
    return subprocess.run(["node", str(root / "node_modules" / "typescript" / "bin" / "tsc"), "-p", config,
                           "--tsBuildInfoFile", str(info)], cwd=root, capture_output=True, text=True, timeout=600)


def test_the_rayfin_tsconfig_is_the_templates(node_modules):
    assert (TEMPLATE / "rayfin" / "tsconfig.json").read_text(encoding="utf-8") == RAYFIN_TSCONFIG


@pytest.mark.parametrize("case", ["shop", "northwind"])
def test_the_generated_project_compiles_with_the_pinned_versions(case, shop, node_modules, tmp_path):
    """`tsc -p rayfin/tsconfig.json` is the compile `rayfin up` runs (it emits the entity classes it applies);
    `tsc -p tsconfig.json` is the app's type check, over src/: the wiring, the page, and through the page's and the
    wiring's `import type` the connector's schema.ts and entity classes."""
    if case == "shop":
        files = rayfin_files(shop, "shop")
        page = "src/pages/OrderItemsPage.tsx"
    else:
        fx = json.loads((SCHEMAS / "northwind.json").read_text(encoding="utf-8"))
        rows = [("dbo", t["name"], col, typ, i) for t in fx["tables"] for i, (col, typ) in enumerate(t["columns"], 1)]
        p = plan(Schema.from_information_schema(rows, schema="dbo"))
        files = rayfin_files(p, "north-wind", page_table="employees")
        page = "src/pages/EmployeesPage.tsx"
    root = _project(tmp_path / case, node_modules, files)
    assert (root / page).exists()
    r = _tsc(root, "rayfin/tsconfig.json")
    assert r.returncode == 0, r.stdout + r.stderr
    compiled = root / "rayfin" / ".temp" / "compiled" / "connectors"
    assert any(compiled.rglob("schema.js")), "the connector's compiled entities are what `rayfin up` applies"
    r = _tsc(root, "tsconfig.json")
    assert r.returncode == 0, r.stdout + r.stderr


def test_the_compile_check_fails_on_a_wrong_column(shop, node_modules, tmp_path):
    """The check is not vacuous: a column the entity does not have fails the app's type check."""
    files = rayfin_files(shop, "shop")
    page = "src/pages/OrderItemsPage.tsx"
    files[page] = files[page].replace("'quantity', 'timestamp'] as const", "'quantity', 'nope'] as const")
    root = _project(tmp_path / "wrong", node_modules, files)
    r = _tsc(root, "tsconfig.json")
    assert r.returncode != 0 and "nope" in r.stdout
