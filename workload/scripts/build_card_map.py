"""Krusgraph (n173): the Model editor draws the plan with the MCP Apps cards' own map code, not a second renderer.

The cards (fabric_backend/mcp_apps_pictures.py, rounds n170 and n172) draw the map with the chat demo's placement and
picture() cut from fabric_backend/static/chat-demo.js, plus the cards' labels, legend and list (DRAW_JS, CSS). The
mascots are the site's figures as flat SVG (fabric_backend/mcp_apps_mascots.py, from static/mascots.js). This script
writes that same code, unchanged, as one TypeScript module the editor imports:

    workload/Workload/app/items/ModelItem/cardMap.generated.ts

Run it from the repository root after the cards' map or the mascots change:

    python workload/scripts/build_card_map.py           # writes the file
    python workload/scripts/build_card_map.py --check   # exit 1 when the file is stale

tests/test_workload_check.py fails while the file differs from what this script writes, so the editor's map and the
cards' map cannot drift apart. The editor's own additions (key check states on the tables, accepted links) are in
cardMap.ts and ModelItem.scss, outside the generated file.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = "workload/Workload/app/items/ModelItem/cardMap.generated.ts"

# What the cards' script around DRAW_JS provides (mcp_apps.py READ_JS, the cards' el()); the same behaviour.
HELPERS = r"""
  function isObj(x) { return !!x && typeof x === "object" && !Array.isArray(x); }
  function looksJson(s) { return /^\s*[\[{]/.test(s); }
  function readable(s) { return typeof s === "string" && s.trim() && !looksJson(s) ? s : ""; }
  function el(tag, text, cls) { var e = document.createElement(tag); if (text != null) e.textContent = String(text); if (cls) e.className = cls; return e; }
  function renderActions() {}
"""


def render() -> str:
    sys.path.insert(0, str(ROOT))
    from fabric_backend import mcp_apps_mascots as M, mcp_apps_pictures as P
    figures = {k: M.svg(k, "rest") for k in M.KINDS}          # a pose is the data-pose attribute, drawn by MASCOT_CSS
    colours = {k: {c: M.kinds()[k][c] for c in ("fill", "dark", "light")} for k in M.KINDS}
    return (
        "// @ts-nocheck\n"
        "/* GENERATED by workload/scripts/build_card_map.py from fabric_backend/mcp_apps_pictures.py (the MCP Apps cards'\n"
        " * map, n170/n172, with the chat demo's drawing cut from fabric_backend/static/chat-demo.js) and\n"
        " * fabric_backend/mcp_apps_mascots.py (the site's mascots). Do not edit: run the script; tests/test_workload_check.py\n"
        " * fails when this file is stale. Typed use goes through cardMap.ts. */\n"
        "/* eslint-disable */\n"
        + HELPERS + P.picture_js() + P.DRAW_JS +
        "\nexport { drawMap, kgRelText, STATE_WORD };\n"
        f"export const MAP_CSS = {json.dumps(P.CSS)};\n"
        f"export const MASCOT_CSS = {json.dumps(M.CSS)};\n"
        f"export const MASCOT_NAMES = {json.dumps(M.NAMES)};\n"
        f"export const MASCOT_COLOURS = {json.dumps(colours)};\n"
        f"export const MASCOT_GLAD = {json.dumps(list(M.GLAD))};\n"
        f"export const MASCOT_POSES = {json.dumps(list(M.POSES))};\n"
        f"export const MASCOT_SVG = {json.dumps(figures, indent=1)};\n"
        f"export const WORDS_WITH_ARGUMENTS = {M.ARGS_SAID_JS};\n"
    )


def main(argv: list[str]) -> int:
    text, path = render(), ROOT / OUT
    if "--check" in argv:
        same = path.exists() and path.read_text(encoding="utf-8") == text
        print(f"{OUT}: {'current' if same else 'STALE: run python workload/scripts/build_card_map.py'}")
        return 0 if same else 1
    path.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({len(text)} characters)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
