"""A data dictionary in Markdown for hand-over: tables, columns and types, keys and relationships with their rules,
keyless tables, ambiguous columns, the ER diagram, and — when given — the counts from `evidence.validate`.
No business meaning is written; a blank Description column is left for the owner."""
from __future__ import annotations

from .infer import Plan, RULES


def _cell(s) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def data_dictionary(plan: Plan, source: str, schema: str, validation: dict | None = None, product: str = "Krusgraph") -> str:
    refs: dict[tuple[str, str], list[str]] = {}
    for r in plan.relationships:
        for c in r.source_cols:
            refs.setdefault((r.source, c), []).append(f"{r.target}.{'+'.join(r.target_cols)} ({r.rule})")
    out = [f"# Data dictionary: {source} / {schema}", "",
           f"Generated by {product} from the source's metadata (table and column names and types). Keys and relationships are "
           "inferred where the source declares none; every one names its rule. Descriptions are left blank on purpose — fill "
           "them in with the business meaning.", "",
           "## Summary", "", f"- {plan.summary().splitlines()[0]}",
           f"- Tables without a key: {', '.join(plan.keyless) if plan.keyless else 'none'}",
           f"- Ambiguous columns (not applied): {len(plan.ambiguous)}"]
    if validation:
        out.append(f"- Checked against the data: {validation.get('summary', '')}")
    out += ["", "## Tables", ""]
    for t in plan.schema:
        key = plan.keys.get(t.name, ([], ""))
        out += [f"### {t.name}", "",
                f"Key: {'+'.join(key[0]) + ' (rule ' + key[1] + ')' if key[0] else 'none (rule K3)'}", "",
                "| Column | Type | Key | Refers to | Description |", "| --- | --- | --- | --- | --- |"]
        for c in t.columns:
            out.append(f"| {_cell(c.name)} | {_cell(c.data_type)} | {'yes' if c.name in key[0] else ''} | "
                       f"{_cell(', '.join(refs.get((t.name, c.name), [])))} |  |")
        out.append("")
    out += ["## Keys", "", "| Table | Columns | Rule | Meaning |", "| --- | --- | --- | --- |"]
    for t in plan.schema:
        cols, rule = plan.keys.get(t.name, ([], "K3"))
        out.append(f"| {_cell(t.name)} | {_cell('+'.join(cols)) or '—'} | {rule} | {_cell(RULES.get(rule, ''))} |")
    out += ["", "## Relationships", ""]
    if plan.relationships:
        out += ["| From | Columns | To | Columns | Rule | Field on from / on to |", "| --- | --- | --- | --- | --- | --- |"]
        for r in plan.relationships:
            out.append(f"| {_cell(r.source)} | {_cell('+'.join(r.source_cols))} | {_cell(r.target)} | {_cell('+'.join(r.target_cols))} "
                       f"| {r.rule} | {_cell(r.field_name)} / {_cell(r.reverse_name)} |")
    else:
        out.append("None inferred.")
    out += ["", "## Tables without a key", ""]
    out += [f"- {t}: can be queried and can point at other tables; nothing can point at it. Give `keys` to change that." for t in plan.keyless] or ["None."]
    out += ["", "## Ambiguous columns", ""]
    out += [f"- {a['table']}.{a['column']} could point at {', '.join(a['candidates'])} ({a['rule']}); not applied — confirm one with `confirmed`."
            for a in plan.ambiguous] or ["None."]
    if validation:
        out += ["", "## Checked against the data", "", validation.get("note", ""), "",
                "| Table | Key | Rows | NULLs | Distinct | Verdict |", "| --- | --- | --- | --- | --- | --- |"]
        for k in validation.get("keys", []):
            out.append(f"| {_cell(k['table'])} | {_cell('+'.join(k['columns']))} | {k['rows']} | {k['nulls']} | {k['distinct']} | {_cell(k['verdict'])} |")
        out += ["", "| From | Columns | To | Rows with a value | Orphans | Verdict |", "| --- | --- | --- | --- | --- | --- |"]
        for r in validation.get("relationships", []):
            out.append(f"| {_cell(r['source'])} | {_cell('+'.join(r['columns']))} | {_cell(r['target'])} | {r['rows_with_value']} | {r['orphans']} | {_cell(r['verdict'])} |")
    from . import graphs
    a = graphs.analyze(plan, validation)
    out += ["", "## Roles, subject areas and ambiguity", "", a["summary"], "", "| Table | Role | Why |", "| --- | --- | --- |"]
    out += [f"| {_cell(t.name)} | {a['roles'][t.name]['role']} | {_cell(a['roles'][t.name]['why'])} |" for t in plan.schema]
    out += ["", "Subject areas (label propagation on the relationship graph, named after the most central table):", ""]
    out += [f"- {g['name']}: {', '.join(g['tables'])}" for g in a["areas"]]
    out += ["", a["ambiguity"]["note"] + "."]
    out += [f"- cycle through {' - '.join(c['tables'])}, closed by {c['closed_by']}" for c in a["ambiguity"]["cycles"]]
    if a["inactive_relationships"]:
        out += ["", "Relationships a semantic model would have to leave inactive (lower certainty on a cycle):", ""]
        out += [f"- {e['source']}.{'+'.join(e['columns'])} -> {e['target']} ({e['rule']}, certainty {e['certainty']}): {e['why']}" for e in a["inactive_relationships"]]
    out += ["", "## Diagram", "", "```mermaid", plan.mermaid(), "```", "",
            "## Rules", "", "| Rule | Meaning |", "| --- | --- |"]
    out += [f"| {code} | {_cell(text)} |" for code, text in RULES.items()]
    out.append("")
    return "\n".join(out)
