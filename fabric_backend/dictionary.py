"""A data dictionary in Markdown for hand-over: tables, columns and types, keys and relationships with their rules,
keyless tables, ambiguous columns, the ER diagram, and — when given — the counts from `evidence.validate`.
No business meaning is written; a blank Description column is left for the owner."""
from __future__ import annotations

from .infer import PACK_RULES, Plan, RULES


def _cell(s) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def data_dictionary(plan: Plan, source: str, schema: str, validation: dict | None = None, product: str = "Krusgraph",
                    tables: set[str] | None = None) -> str:
    """The whole plan's document, or with `tables` (names) the part about those tables: their columns, keys and the
    relationships that touch them. Roles, subject areas and cycles are always the whole plan's, then filtered, so a
    table keeps the role it has in the schema (data_dictionary with tables=["orders"] once called orders isolated)."""
    from . import graphs
    from .compact import sub_plan
    whole = plan
    a = graphs.analyze(whole, validation)
    keep = set(tables) if tables is not None else None
    plan = sub_plan(whole, keep)

    def touches(*names) -> bool:
        return keep is None or any(n in keep for n in names)
    refs: dict[tuple[str, str], list[str]] = {}
    for r in plan.relationships:
        for c in r.source_cols:
            refs.setdefault((r.source, c), []).append(f"{r.target}.{'+'.join(r.target_cols)} ({r.rule})")
    out = [f"# Data dictionary: {source} / {schema}", "",
           f"Generated by {product} from the source's metadata (table and column names and types). Keys and relationships are "
           "inferred where the source declares none; every one names its rule. Descriptions are left blank on purpose — fill "
           "them in with the business meaning.", "",
           "## Summary", "", f"- {whole.summary().splitlines()[0]}"]
    if keep is not None:
        out.append(f"- Shown: {', '.join(t.name for t in plan.schema)} ({len(plan.schema)} of {len(whole.schema)} tables) and the "
                   f"{len(plan.relationships)} relationship(s) that touch them; roles and subject areas are the whole schema's")
    out += [f"- Tables without a key: {', '.join(plan.keyless) if plan.keyless else 'none'}",
           f"- Ambiguous columns (not applied): {len(plan.ambiguous)}"]
    if validation:
        out.append(f"- Checked against the data: {validation.get('summary', '')}")
    out += ["", "## Tables", ""]
    for t in plan.schema:
        key = plan.keys.get(t.name, ([], ""))
        out += [f"### {t.name}", "",
                f"Key: {'+'.join(key[0]) + ' (rule ' + key[1] + ')' if key[0] else 'none (rule K3)'}", "",
                "| Column | Type | Key | Refers to | Description |", "| --- | --- | --- | --- | --- |"]
        for c in t.columns:
            out.append(f"| {_cell(c.name)} | {_cell(c.data_type)} | {'yes' if c.name in key[0] else ''} | "
                       f"{_cell(', '.join(refs.get((t.name, c.name), [])))} |  |")
        out.append("")
    out += ["## Keys", "", "| Table | Columns | Rule | Meaning |", "| --- | --- | --- | --- |"]
    for t in plan.schema:
        cols, rule = plan.keys.get(t.name, ([], "K3"))
        out.append(f"| {_cell(t.name)} | {_cell('+'.join(cols)) or '—'} | {rule} | {_cell({**RULES, **PACK_RULES}.get(rule, ''))} |")
    out += ["", "## Relationships", ""]
    if plan.relationships:
        out += ["| From | Columns | To | Columns | Rule | Field on from / on to |", "| --- | --- | --- | --- | --- | --- |"]
        for r in plan.relationships:
            out.append(f"| {_cell(r.source)} | {_cell('+'.join(r.source_cols))} | {_cell(r.target)} | {_cell('+'.join(r.target_cols))} "
                       f"| {r.rule} | {_cell(r.field_name)} / {_cell(r.reverse_name)} |")
    else:
        out.append("None inferred.")
    if plan.extended:                                                    # only with a knowledge pack: other answers are unchanged
        out += ["", "Joins that are not on the target's key (from the pack; a GraphQL API or semantic model built from the plan "
                "does not carry them):", "", "| From | To | Kind | Join |", "| --- | --- | --- | --- |"]
        out += [f"| {_cell(r.source)} | {_cell(r.target)} | {r.kind} | {_cell(r.join_sql())} |" for r in plan.extended]
    out += ["", "## Tables without a key", ""]
    out += [f"- {t}: can be queried and can point at other tables; nothing can point at it. Give `keys` to change that." for t in plan.keyless] or ["None."]
    out += ["", "## Ambiguous columns", ""]
    out += [f"- {a['table']}.{a['column']} could point at {', '.join(a['candidates'])} ({a['rule']}); not applied — confirm one with `confirmed`."
            for a in plan.ambiguous] or ["None."]
    if validation:
        out += ["", "## Checked against the data", "", validation.get("note", ""), "",
                "| Table | Key | Rows | NULLs | Distinct | Verdict |", "| --- | --- | --- | --- | --- | --- |"]
        for k in (k for k in validation.get("keys", []) if touches(k["table"])):
            out.append(f"| {_cell(k['table'])} | {_cell('+'.join(k['columns']))} | {k['rows']} | {k['nulls']} | {k['distinct']} | {_cell(k['verdict'])} |")
        out += ["", "| From | Columns | To | Rows with a value | Orphans | Verdict |", "| --- | --- | --- | --- | --- | --- |"]
        for r in (r for r in validation.get("relationships", []) if touches(r["source"], r["target"])):
            out.append(f"| {_cell(r['source'])} | {_cell('+'.join(r['columns']))} | {_cell(r['target'])} | {r['rows_with_value']} | {r['orphans']} | {_cell(r['verdict'])} |")
    out += ["", "## Roles, subject areas and ambiguity", "", ("Over the whole schema: " if keep is not None else "") + a["summary"], "",
            "| Table | Role | Why |", "| --- | --- | --- |"]
    out += [f"| {_cell(t.name)} | {a['roles'][t.name]['role']} | {_cell(a['roles'][t.name]['why'])} |" for t in plan.schema]
    out += ["", "Subject areas (label propagation on the relationship graph, named after the most central table):", ""]
    out += [f"- {g['name']}: {', '.join(g['tables'])}" for g in a["areas"] if touches(*g["tables"])]
    out += ["", a["ambiguity"]["note"] + "."]
    out += [f"- cycle through {' - '.join(c['tables'])}, closed by {c['closed_by']}" for c in a["ambiguity"]["cycles"] if touches(*c["tables"])]
    inactive = [e for e in a["inactive_relationships"] if touches(e["source"], e["target"])]
    if inactive:
        out += ["", "Relationships a semantic model would have to leave inactive (lower certainty on a cycle):", ""]
        out += [f"- {e['source']}.{'+'.join(e['columns'])} -> {e['target']} ({e['rule']}, certainty {e['certainty']}): {e['why']}" for e in inactive]
    if plan.pack:                                                        # only with SAP tables: other answers are unchanged
        from . import sap_pack
        pk = sap_pack.load(plan.pack["pack"])
        out += ["", f"## Known from the {plan.pack['pack']} pack", "",
                f"{len(plan.pack['tables'])} table(s) recognised; their keys and relationships come from public documentation "
                "(rule \"SAP pack\") and are documented, not verified: check them with validate_plan.", ""]
        out += [f"- {t['title']}: {t['text']}" for t in pk["traps"]]
        out += [f"- not applied: {n['source']} -> {n['target']}: {n['why']}" for n in plan.pack["not_applied"]]
        out += ["", "Sources:", ""] + [f"- {pk['sources'][i]['title']} ({pk['sources'][i]['url']})" for i in plan.pack["sources"]]
    out += ["", "## Diagram", "", "```mermaid", plan.mermaid(), "```", "",
            "## Rules", "", "| Rule | Meaning |", "| --- | --- |"]
    out += [f"| {code} | {_cell(text)} |" for code, text in RULES.items()]
    if plan.pack:
        out += [f"| {code} | {_cell(text)} |" for code, text in PACK_RULES.items()]
    out.append("")
    return "\n".join(out)
